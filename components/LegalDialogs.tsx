'use client';

import { createContext, useCallback, useContext, useMemo, useState, type ReactNode } from 'react';
import { CONFIG, LEGAL_UPDATED } from '@/lib/config';
import { Dialog } from './Dialog';

export type LegalDocId = 'docPrivacy' | 'docTerms' | 'docA11y';

interface LegalContextValue {
  open: (id: LegalDocId) => void;
}

const LegalContext = createContext<LegalContextValue | null>(null);

/** פותח מסמך משפטי מכל מקום בעץ. */
export function useLegal(): LegalContextValue {
  const ctx = useContext(LegalContext);
  if (!ctx) throw new Error('useLegal must be used inside <LegalProvider>');
  return ctx;
}

const Mail = () => (
  <a href={`mailto:${CONFIG.email}`}>
    <bdi>{CONFIG.email}</bdi>
  </a>
);
const Phone = () => <bdi>{CONFIG.phone}</bdi>;

/** תאריך העדכון מגיע מקבוע אחד, כדי שלא יישאר תאריך מת בדף. */
function UpdatedStamp({ label }: { label: string }) {
  const formatted = useMemo(
    () =>
      new Date(LEGAL_UPDATED).toLocaleDateString('he-IL', {
        year: 'numeric',
        month: 'long',
        day: 'numeric',
      }),
    [],
  );
  return (
    <p className="doc__updated">
      {label} <span>{formatted}</span>
    </p>
  );
}

